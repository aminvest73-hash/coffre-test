//     (toujours écrit après « ton » ou « mon », qui vont aux deux) ;
//   - {=cle} : recopie un autre texte de la même langue (le nom d'un bouton, pour qu'une phrase qui le cite ne
//     puisse pas s'en écarter) ;
//   - {autre} : une valeur donnée par la page (le nom du jeu, un montant, une adresse).
// Les deux langues ont exactement les mêmes clés (les essais le vérifient).
//
// Sur un écran qui engage le joueur (entrer dans un jeu, confirmer un envoi ou une opération), les phrases qui
// disent une limite gardent leur sens exact dans les deux langues : ce que la fenêtre a vérifié, ce qu'elle ne lit
// pas, ce qui est envoyé et ce qui ne l'est pas.
//
