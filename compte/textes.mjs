const propre = (o, c) => Object.prototype.hasOwnProperty.call(o, c);
// Vrai si ce texte existe (les deux langues ont les mêmes clés).
export const existe = (cle) => typeof cle === 'string' && propre(TEXTES.fr, cle);
// La langue d'un navigateur : le français s'il le dit, l'anglais sinon. `defaut` ne sert que s'il ne dit rien.
export function langueDuNavigateur(dite, defaut) {
  if (typeof dite !== 'string' || !dite) return propre(TEXTES, defaut) ? defaut : 'fr';
  return /^fr(-|_|$)/i.test(dite) ? 'fr' : 'en';
}
// Le texte d'une clé, dans une langue, avec ses valeurs. `surTelephone` choisit le mot pour {appareil}.
// Une clé inconnue rend un texte vide, une valeur absente aussi. Les valeurs sont posées telles quelles et ne
// sont pas relues : une accolade dans le nom d'un jeu reste une accolade.
export function texte(langue, cle, valeurs, surTelephone) {
  const l = propre(TEXTES, langue) ? langue : 'fr', d = TEXTES[l], m = MOTS[l];
  if (!propre(d, cle)) return '';
  let s = d[cle];
  for (let i = 0; i < 3 && s.includes('{='); i++) s = s.replace(/\{=([A-Za-z0-9_]+)\}/g, (_, c) => (propre(d, c) ? d[c] : ''));
  return s.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (_, nom) => {
    if (nom === 'appareil') return surTelephone ? m.telephone : m.appareil;
    if (nom === 'compte' || nom === 'un_compte') return m[nom];
    return valeurs && propre(valeurs, nom) && valeurs[nom] !== null && valeurs[nom] !== undefined ? String(valeurs[nom]) : '';
  });
}
